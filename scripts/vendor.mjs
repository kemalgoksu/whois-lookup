import { build } from 'esbuild';
import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(path.join(root, 'vendor'), { recursive: true });
const pkg = JSON.parse(await readFile(path.join(root, 'node_modules/tldts/package.json'), 'utf8'));
await build({
  entryPoints: [path.join(root, 'node_modules/tldts/dist/es6/index.js')],
  outfile: path.join(root, 'vendor/tldts.js'),
  bundle: true,
  format: 'iife',
  globalName: 'tldts',
  minify: false,
  target: 'chrome103',
  banner: { js: `// tldts ${pkg.version}; MIT. Generated by npm run vendor; do not edit.` }
});
for (const name of ['tldts', 'tldts-core']) {
  await copyFile(path.join(root, 'node_modules', name, 'LICENSE'), path.join(root, 'vendor', `${name}.LICENSE`));
}
await writeFile(path.join(root, 'vendor/README.md'), `# Bundled domain parser\n\ntldts ${pkg.version}, https://github.com/remusao/tldts, MIT licensed.\n\nRegenerate readable tldts.js with Node 22+: npm ci --ignore-scripts, then npm run vendor.\nExact dependencies and integrity hashes are recorded in package-lock.json.\nThe extension loads only this local bundle; it does not download code or suffix lists.\nUpdate the pinned dependency and regenerate the bundle to refresh the public suffix data.\n`);
